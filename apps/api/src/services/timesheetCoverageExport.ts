/**
 * Excel for the timesheet-coverage report: a "Coverage" sheet and a "Timesheet detail" sheet.
 *
 * WHY THE EXPORT IS BUILT FROM THE SAME ASSEMBLY AS THE SCREEN: the file and the screen must be the
 * same report. `buildTimesheetCoverageReport(..., { includeAllRows: true })` is called here, which is
 * the ONE difference — every row, no page — so the workbook's row count is the assembly's row count
 * by construction, and a test asserts exactly that. Paging is a screen affordance; a download that
 * silently carried one page would be a report that lies by omission.
 *
 * The provenance block (period, filters, scope, who generated it, and the definitions of every
 * figure and status) is written ONTO BOTH SHEETS rather than into a third "notes" sheet: a file
 * mailed on its own has to explain itself where the numbers are.
 */

import ExcelJS from "exceljs";
import type { CoverageRow, TimesheetCoverageReport } from "./timesheetCoverageReport";

/** A value a worksheet cell may carry. `Date` (not a serial number) is what makes a date a date. */
type CellValue = string | number | Date | null;

type SheetColumn<T> = {
  header: string;
  width: number;
  numFmt?: string;
  /** The header's colour band. Groups the columns the same way the screen's header does. */
  tone?: HeaderTone;
  value: (row: T) => CellValue;
};

/** Header bands. A workbook is read on a screen and printed on paper, so these stay LIGHT (a band,
 *  not a block): the ink is dark enough for AA on its own fill, and the fills are pale enough that
 *  the numbers under them are never fighting the header for attention. */
type HeaderTone = "id" | "total" | "filled" | "gap" | "overheads" | "combined" | "status";

const HEADER_TONES: Record<HeaderTone, { fill: string; ink: string }> = {
  id: { fill: "FFE9EEF3", ink: "FF14212B" },
  total: { fill: "FFD7EFED", ink: "FF084441" },
  combined: { fill: "FFE4F1EC", ink: "FF084441" },
  overheads: { fill: "FFFFF4E5", ink: "FF7A4009" },
  filled: { fill: "FFE3F6EC", ink: "FF12603B" },
  gap: { fill: "FFFDE8E6", ink: "FF9B2C25" },
  status: { fill: "FFEFF3F6", ink: "FF14212B" },
};

/** `YYYY-MM-DD` -> a real Date so Excel holds a DATE (sortable, formattable), never text. */
function dateCell(iso: string): Date {
  return new Date(`${iso}T00:00:00.000Z`);
}

/** Percentages are written as FRACTIONS with a percent number format, never as pre-multiplied text. */
function fmtPct(value: number): string {
  return `${(value * 100).toFixed(1)}%`;
}

/**
 * The download filename, e.g. `workforce-timesheet-coverage_2026-10-01_to_2026-10-31.xlsx`.
 * The PERIOD is in the name because that is what distinguishes two runs of this report; a file found
 * in a downloads folder months later still says which dates it covers.
 */
export function timesheetCoverageFilename(report: TimesheetCoverageReport): string {
  return `workforce-timesheet-coverage_${report.from}_to_${report.to}.xlsx`;
}

/** The two-line statement written above the data on each sheet. */
function provenancePairs(
  report: TimesheetCoverageReport
): Array<{ label: string; value: CellValue; numFmt?: string }> {
  return [
    { label: "Report", value: "Timesheet coverage by date" },
    { label: "Period", value: `${report.from} to ${report.to} (${report.days.length} day(s))` },
    ...report.provenance.filters.map((filter) => ({ label: filter.label, value: filter.value })),
    { label: "Scope", value: report.provenance.scope },
    {
      label: "Generated by",
      value: `${report.provenance.generatedBy.name} (${report.provenance.generatedBy.role})`,
    },
    { label: "Generated at", value: new Date(report.generatedAt) },
    { label: "", value: "" },
    { label: "Employees in scope", value: report.totals.employees },
    { label: "Employee-days in the period", value: report.totals.employeeDays },
    { label: "Filled days", value: report.totals.filledDays },
    { label: "Not-filled days", value: report.totals.notFilledDays },
    { label: "Employees with NO filled day", value: report.totals.employeesWithNoFilledDay },
    { label: "Filled % of employee-days", value: report.totals.filledPct, numFmt: "0.0%" },
    { label: "", value: "" },
    { label: "Population", value: report.definitions.population },
    { label: "Regular hours", value: report.definitions.hours.regular },
    { label: "Overtime hours", value: report.definitions.hours.overtime },
    { label: "Overheads", value: report.definitions.hours.overheads },
    { label: "Combined hours", value: report.definitions.hours.combined },
    { label: "Duplicate sheets", value: report.definitions.duplicateSheets },
    ...report.definitions.statuses.map((entry) => ({
      label: `Status — ${entry.status}`,
      value: entry.meaning,
    })),
    ...report.definitions.notes.map((note) => ({ label: "Note", value: note })),
  ];
}

/** Write the provenance block in columns A/B starting at row 1, and return the first free row. */
function addProvenance(sheet: ExcelJS.Worksheet, report: TimesheetCoverageReport): number {
  sheet.getColumn(1).width = 30;
  sheet.getColumn(2).width = 92;
  const pairs = provenancePairs(report);
  pairs.forEach((pair, index) => {
    const row = sheet.getRow(index + 1);
    row.getCell(1).value = pair.label;
    row.getCell(1).font = { bold: true };
    row.getCell(2).value = pair.value;
    if (pair.numFmt) row.getCell(2).numFmt = pair.numFmt;
    row.getCell(2).alignment = { wrapText: true, vertical: "top" };
  });
  return pairs.length + 2;
}

/** A frozen-header data table written below the provenance block. */
function addTable<T>(
  sheet: ExcelJS.Worksheet,
  startRow: number,
  columns: SheetColumn<T>[],
  rows: readonly T[]
): void {
  columns.forEach((column, index) => {
    // Columns 1 and 2 already carry the provenance block's widths, so the table only widens them.
    sheet.getColumn(index + 1).width = Math.max(Number(sheet.getColumn(index + 1).width ?? 0), column.width);
  });

  const headerRow = sheet.getRow(startRow);
  columns.forEach((column, index) => {
    const cell = headerRow.getCell(index + 1);
    cell.value = column.header;
    const tone = column.tone ? HEADER_TONES[column.tone] : null;
    cell.font = { bold: true, ...(tone ? { color: { argb: tone.ink } } : {}) };
    if (tone) {
      cell.fill = { type: "pattern", pattern: "solid", fgColor: { argb: tone.fill } };
    }
    cell.alignment = { vertical: "middle", wrapText: true };
  });

  rows.forEach((row, rowIndex) => {
    const added = sheet.getRow(startRow + 1 + rowIndex);
    columns.forEach((column, index) => {
      const cell = added.getCell(index + 1);
      cell.value = column.value(row);
      if (column.numFmt) cell.numFmt = column.numFmt;
    });
  });

  sheet.views = [{ state: "frozen", ySplit: startRow }];
  if (rows.length > 0) {
    sheet.autoFilter = {
      from: { row: startRow, column: 1 },
      to: { row: startRow + rows.length, column: columns.length },
    };
  }
  if (startRow > 1) headerRow.font = { bold: true };
}

/** The detail columns: the operator's own layout, one Regular/OT pair per Project. */
function detailColumns(report: TimesheetCoverageReport): SheetColumn<CoverageRow>[] {
  const projectColumns: SheetColumn<CoverageRow>[] = report.projects.flatMap((project) => [
    {
      header: `${project.name} — Regular`,
      width: 16,
      numFmt: "0.00",
      value: (row) => row.projectHours[project.colorKey] ?? 0,
    },
    {
      header: `${project.name} — OT`,
      width: 12,
      numFmt: "0.00",
      value: (row) => row.projectOtHours[project.colorKey] ?? 0,
    },
  ]);

  return [
    { header: "Date", width: 12, numFmt: "dd-mm-yyyy", tone: "id", value: (row) => dateCell(row.date) },
    { header: "Department", width: 22, tone: "id", value: (row) => row.department.name },
    { header: "Section", width: 20, tone: "id", value: (row) => row.section?.name ?? "No section" },
    { header: "Supervisor", width: 22, tone: "id", value: (row) => (row.supervisors.length ? row.supervisors.join(", ") : "-") },
    { header: "EC No", width: 14, tone: "id", value: (row) => row.employee.ecNo },
    { header: "Employee name", width: 30, tone: "id", value: (row) => row.employee.name },
    ...projectColumns,
    { header: "Total Project hours — Regular", width: 16, numFmt: "0.00", tone: "total", value: (row) => row.regularTotal },
    { header: "Total Project hours — OT", width: 14, numFmt: "0.00", tone: "total", value: (row) => row.otTotal },
    { header: "Total Project hours — Total", width: 14, numFmt: "0.00", tone: "total", value: (row) => row.totalHours },
    { header: "Overheads", width: 12, numFmt: "0.00", tone: "overheads", value: (row) => row.overheads },
    { header: "Combined Hours", width: 14, numFmt: "0.00", tone: "combined", value: (row) => row.combinedHours },
    { header: "Approval Status", width: 16, tone: "status", value: (row) => row.status },
    // Last, because it is the only free-text column: the numbers and the status keep their aligned block, and the
    // supervisor's reason sits at the edge where it does not disturb a scan down the hours. One row is one
    // employee-day, so this is the remark verbatim — stored whether or not the day carried overtime.
    { header: "Remarks", width: 50, tone: "id", value: (row) => row.remarks ?? "" },
  ];
}

/**
 * Build the workbook. Both sheets carry the provenance block, so a single sheet printed or mailed on
 * its own still states its own period, scope and definitions.
 */
export async function buildTimesheetCoverageXlsx(report: TimesheetCoverageReport): Promise<Buffer> {
  // A PAGED report must never become a workbook. The screen pages at 50 rows because a period holds
  // thousands; if a paged report ever reached here, the download would silently be one page of the
  // report — a file that lies by omission, which is the one failure nobody notices. Refusing is
  // better than a partial file, and the caller's fix is one flag (`includeAllRows: true`).
  if (report.rows.length !== report.rowTotal) {
    throw new Error(
      `Refusing to export a partial report: ${report.rows.length} of ${report.rowTotal} rows. Build it with { includeAllRows: true }.`
    );
  }
  const workbook = new ExcelJS.Workbook();
  workbook.creator = report.provenance.generatedBy.name;
  workbook.created = new Date(report.generatedAt);

  /* ---- Sheet 1: Coverage, Department > Section ------------------------------------------- */
  const coverage = workbook.addWorksheet("Coverage");
  const coverageStart = addProvenance(coverage, report);
  addTable(
    coverage,
    coverageStart,
    [
      { header: "Department", width: 26, tone: "id", value: (row) => row.department.name },
      { header: "Section", width: 24, tone: "id", value: (row) => row.section?.name ?? "No section" },
      { header: "Employees", width: 12, numFmt: "0", tone: "id", value: (row) => row.employees },
      { header: "Employee-days", width: 15, numFmt: "0", tone: "id", value: (row) => row.employeeDays },
      { header: "Filled days", width: 12, numFmt: "0", tone: "filled", value: (row) => row.filledDays },
      { header: "Not-filled days", width: 15, numFmt: "0", tone: "gap", value: (row) => row.notFilledDays },
      { header: "Filled %", width: 11, numFmt: "0.0%", tone: "filled", value: (row) => row.filledPct },
      {
        header: "Employees with at least one filled day",
        width: 22,
        numFmt: "0",
        tone: "filled",
        value: (row) => row.employeesWithFilledDay,
      },
      { header: "Employees with NO filled day", width: 22, numFmt: "0", tone: "gap", value: (row) => row.employeesWithNoFilledDay },
    ],
    report.coverage
  );

  /* ---- Sheet 2: the detail rows ------------------------------------------------------------ */
  const detail = workbook.addWorksheet("Timesheet detail");
  const detailStart = addProvenance(detail, report);
  addTable(detail, detailStart, detailColumns(report), report.rows);

  const buffer = await workbook.xlsx.writeBuffer();
  return Buffer.from(buffer);
}

/** Exported for the tests: the header row of the detail sheet, without building a workbook. */
export function detailHeaders(report: TimesheetCoverageReport): string[] {
  return detailColumns(report).map((column) => column.header);
}

/** Exported for the tests and the screen: a human sentence for the filled share. */
export function filledShareLabel(report: TimesheetCoverageReport): string {
  return `${fmtPct(report.totals.filledPct)} of employee-days filled (${report.totals.filledDays} of ${report.totals.employeeDays})`;
}
